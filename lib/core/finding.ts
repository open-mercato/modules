// Lint `backend-route-collision` (round 14): the same refusal of `generate`, predicted from the facts

/** Code and weight of the lint rule (spec 6.6): a warning, never a verdict, a level or a refusal. */
export const BACKEND_ROUTE_COLLISION = { code: 'backend-route-collision', severity: 'warn' } as const

/**
 * A backend page of the module whose URL a module of a new app already has (round 14): what `generate` refuses in
 * `module add` (DUPLICATE_ROUTE_RE), read statically from the facts of both. `IndexEntry.compat.collisions[line]`.
 */
export interface RouteCollision {
  /** The module's own backend route (`/backend/webhooks`). */
  route: string
  /** The module ID of the app that has the same route (`webhooks`). */
  module: string
  /** The package that registers that module in a new app (`@open-mercato/webhooks`, `@open-mercato/core`). */
  from: string
}

/** A backend route as two pages collide on it: a dynamic segment is a dynamic segment (`[id]`, `[webhookId]`). */
export function backendRouteKey(path: string): string {
  return path.replace(/\[[^\]]*\]/g, '[]').replace(/(.)\/+$/, '$1')
}

/**
 * The module's backend routes that a module of the app has too, in the module's order, one per route. `app` lists the
 * other modules of the app with their backend routes; the module's own package is left out by the caller.
 */
export function backendRouteCollisions(
  own: readonly string[],
  app: readonly { id: string; from: string; routes: readonly string[] }[],
): RouteCollision[] {
  const out: RouteCollision[] = []
  for (const route of own) {
    const key = backendRouteKey(route)
    if (out.some((c) => backendRouteKey(c.route) === key)) continue
    const hit = app.find((m) => m.routes.some((r) => backendRouteKey(r) === key))
    if (hit) out.push({ route, module: hit.id, from: hit.from })
  }
  return out
}

const ownerText = (module: string, from: string): string =>
  from === '@open-mercato/core' ? `the built-in ${module} module` : `the ${module} module (${from})`

/**
 * The static warning of a line (round 14): `Static check: the module adds the backend route /backend/webhooks, which a
 * new app already has from the webhooks module (@open-mercato/webhooks).` The first module the routes collide with is
 * named; more routes are counted. The strip, the install box, the card, `check_compat` and the agent policy print it;
 * `plan_install` names the app it plans for (`this app`, round 15) in its `conflicts`.
 */
export function collisionText(cs: readonly RouteCollision[], app = 'a new app', subject = 'the module'): string | null {
  const first = cs[0]
  if (!first) return null
  const same = cs.filter((c) => c.module === first.module && c.from === first.from)
  const rest = cs.length - same.length
  const routes =
    same.length === 1
      ? `the backend route ${first.route}`
      : same.length === 2
        ? `the backend routes ${same[0]!.route} and ${same[1]!.route}`
        : `the backend routes ${same[0]!.route} and ${same.length - 1} more`
  const more = rest > 0 ? ` ${rest} more backend route${rest > 1 ? 's collide' : ' collides'} with other modules.` : ''
  return `Static check: ${subject} adds ${routes}, which ${app} already has from ${ownerText(first.module, first.from)}.${more}`
}

/**
 * What to fix when `add` broke on a backend route a new app already has (finding of 25 Oct: VER-1 said only `Fix the
 * failing step (add)` while the page named the collision three times): `Nest the backend page /backend/webhooks under
 * a folder of the module's own; a new app already has it from the webhooks module (@open-mercato/webhooks)`, the
 * advice `yarn generate` prints. Null without a collision.
 */
export function collisionFix(cs: readonly RouteCollision[]): string | null {
  const first = cs[0]
  if (!first) return null
  const more = cs.length > 1 ? ` (and ${cs.length - 1} more)` : ''
  return `Nest the backend page ${first.route}${more} under a folder of the module's own; a new app already has it from ${ownerText(first.module, first.from)}`
}

/** The lint message of the rule on the module page (the Hygiene list): `Adds the backend route ... on 0.8 and 0.9 ...`. */
export function collisionLintText(c: RouteCollision, lines: readonly string[]): string {
  const on = lines.length <= 1 ? (lines[0] ?? '') : `${lines.slice(0, -1).join(', ')} and ${lines[lines.length - 1]}`
  return `Adds the backend route ${c.route}, which a new app${on ? ` on ${on}` : ''} already has from ${ownerText(c.module, c.from)}. The generate step refuses two modules with one backend route.`
}

/**
 * The backend route collisions of an entry as the card's `Replaces or conflicts` names them (round 16: the card said
 * `none` while plan_install.conflicts had a `route` item): `backend route /backend/webhooks with the webhooks module
 * (@open-mercato/webhooks) in a new app on 0.8 and 0.9 (static check)`, one item per route and module, its lines in
 * the order `keys` gives. `byLine` is `IndexEntry.compat.collisions`.
 */
export function collisionConflictItems(
  byLine: Readonly<Record<string, readonly RouteCollision[]>> | undefined,
  keys: readonly string[],
): string[] {
  const groups = new Map<string, { c: RouteCollision; keys: string[] }>()
  for (const k of keys)
    for (const c of byLine?.[k] ?? []) {
      const id = `${c.route}|${c.module}|${c.from}`
      const g = groups.get(id) ?? { c, keys: [] }
      if (!g.keys.includes(k)) g.keys.push(k)
      groups.set(id, g)
    }
  return [...groups.values()].map(
    ({ c, keys: on }) =>
      `backend route ${c.route} with ${ownerText(c.module, c.from)} in a new app on ${listAnd(on)} (static check)`,
  )
}

/**
 * The preset the receipts scaffold with, as the finding sentence names it (review r10). Round 14: `the empty preset`,
 * the words of every other sentence of the site (`an app from the empty preset`, `In isolation (empty preset)`); the
 * finding is stored in data/health, so a change here needs a full `yarn om health`.
 */
export const EMPTY_PRESET = 'the empty preset'

const listAnd = (xs: readonly string[]): string =>
  xs.length <= 1 ? (xs[0] ?? '') : `${xs.slice(0, -1).join(', ')} and ${xs[xs.length - 1]}`

/** The route a smoke 403 came from, read from the facts by its required features; null unless exactly one fits. */
export function smokeRouteOf(routes: readonly RouteFact[] | undefined, features: readonly string[]): string | null {
  if (!routes) return null
  const want = [...features].sort().join(' ')
  const hits = routes.filter(
    (r) =>
      r.method === 'GET' &&
      r.requireAuth === true &&
      r.path.startsWith('/api/') &&
      !/[[\]]/.test(r.path) &&
      [...r.requireFeatures].sort().join(' ') === want,
  )
  return hits.length === 1 ? `GET ${hits[0]!.path}` : null
}

/**
 * One sentence that says why a failed step failed, when its excerpt says it plainly; null otherwise (review r9, r10:
 * `GET /api/events needs the workflows.view feature, and the empty preset does not enable the workflows module.`,
 * never a log line with a semicolon, and never `off in a new app`, which the default preset contradicts).
 * Like the classification rules it reads only the excerpt (and the facts for the route), so a better sentence never
 * changes a receipt.
 */
export function explainFailure(
  step: string | null | undefined,
  excerpt: string | null | undefined,
  ctx: ExplainContext = {},
): string | null {
  const dup = step === 'add' || step === 'typecheck' || step === 'build' ? duplicateRoute(excerpt) : null
  if (dup) return duplicateRouteText(dup, ctx)
  if (step !== 'smoke') return null
  const f = forbiddenRoute(excerpt)
  if (!f) return null
  const who = f.route ?? smokeRouteOf(ctx.routes, f.features) ?? 'An API route of the module'
  const needs = `${who} needs the ${listAnd(f.features)} feature${f.features.length > 1 ? 's' : ''}`
  const off = f.modules.filter((m) => ctx.enabledInEmptyPreset?.(m) === false)
  if (off.length === 0) return `${needs}.`
  return `${needs}, and ${EMPTY_PRESET} does not enable the ${listAnd(off)} module${off.length > 1 ? 's' : ''}.`
}

/** The part of a receipt the sentences read. */
export interface FailedStepOf {
  result: { status: string; failedStep: string | null }
  steps: readonly { name: string; excerpt: string | null }[]
}

/** What the failed step printed first (`TS2307 Cannot find module ...`), without the step, or '' when nothing. */
export function stepErrorText(r: FailedStepOf): string {
  const step = r.steps.find((s) => s.name === r.result.failedStep)
  const line = step?.excerpt?.split('\n').find((l) => /error|fail/i.test(l)) ?? step?.excerpt?.split('\n')[0] ?? ''
  // a Yarn progress line (`➤ YN0000: · Yarn 4.17.1`) says nothing (round 13: an excerpt collected before the rule
  // `duplicate-route` started there): the step's name alone, `add failed.`
  if (/^\W*YN0000:/.test(line)) return ''
  const ts = /error (TS\d+): (.*)$/.exec(line)
  return appRelative(ts ? `${ts[1]} ${ts[2]}` : line.replace(/^.*?:\s*/, ''))
}

/**
 * A quoted path inside the cell's app as the app sees it (round 15: `'/home/om-cell/app/node_modules/...'` took a third
 * of the sentence and cut the rest): from `node_modules/` on.
 */
function appRelative(text: string): string {
  return text.replace(/(['"])\/[^'"\s]*?\/(node_modules\/)/g, '$1$2')
}

/**
 * What the failed step of a broken receipt printed first, as the sentence of a line no rule explains (round 15: the
 * strip, the card and `check_compat` gave the cause of the signal in isolation and not of the main verdict):
 * `Typecheck failed: TS7016 Could not find a declaration file for module ...`, the words of the isolation sentence
 * (`isolationText`). Null when the step printed nothing that says more than its name.
 */
export function errorFindingText(r: FailedStepOf | null | undefined, max = 200): string | null {
  if (!r || !r.result.failedStep || r.result.status !== 'broken') return null
  const text = stepErrorText(r)
  if (!text) return null
  const step = r.result.failedStep
  const out = `${step.charAt(0).toUpperCase()}${step.slice(1)} failed: ${text}`
  return out.length > max ? `${out.slice(0, max - 1)}…` : out
}

/** The explanation of a receipt's failed step (`explainFailure` on its own excerpt), or null. */
export function explainReceiptStep(r: FailedStepOf | null | undefined, ctx: ExplainContext = {}): string | null {
  if (!r || !r.result.failedStep || r.result.status !== 'broken') return null
  const step = r.steps.find((s) => s.name === r.result.failedStep)
  return explainFailure(r.result.failedStep, step?.excerpt, ctx)
}

/**
 * What a receipt found on a line that ships the package (review r8, r9): the explanation of its failed step, else what
 * the step printed (`typecheck failed: TS2561 ...`), else `<step> failed.` It follows a colon (`Found while testing on
 * 0.9: GET /api/events needs ...`), so a sentence that starts with `An`, `In`, `The` or `Two` continues in lower
 * case. Null for a receipt
 * that failed nothing.
 */
export function findingText(r: FailedStepOf | null | undefined, ctx: ExplainContext = {}, max = 200): string | null {
  if (!r || !r.result.failedStep || r.result.status === 'verified') return null
  const why = explainReceiptStep(r, ctx)?.replace(/^(An|In|The|Two) /, (w) => w.toLowerCase())
  if (why) return why
  const text = stepErrorText(r)
  const out = `${r.result.failedStep} failed${text ? `: ${text}` : '.'}`
  return out.length > max ? `${out.slice(0, max - 1)}…` : out
}

// ---- host-dependency-duplication (spec 6.6, D34)

export const HOST_DEPENDENCY_DUPLICATION = { code: 'host-dependency-duplication', severity: 'warn' } as const

/** A host package the module bundles in `dependencies` in a version a new app does not resolve to (FitCell). */
export interface HostDuplicate {
  name: string
  moduleRange: string
  appVersion: string
}

/** One bundled host package with the lines a new app resolves another version on, in reading order. */
export interface HostDuplicateFinding extends HostDuplicate {
  lines: string[]
  /** Open Mercato version of each line in `lines`, same order. */
  om: string[]
}

/**
 * The bundled host packages of an entry across the lines (`EntryContext.fit`), one item per package and versions, so
 * the module page, the card and the detail file can name the cause the receipts only show inside a log path
 * (D34: `the cause of the consents failure is visible`). `lines` gives the reading order and the versions.
 */
export function hostDuplicateFindings(
  fit: Readonly<Record<string, { hostDuplicates: readonly HostDuplicate[] } | null | undefined>>,
  lines: readonly { key: string; version: string }[],
): HostDuplicateFinding[] {
  const out: HostDuplicateFinding[] = []
  for (const l of lines)
    for (const d of fit[l.key]?.hostDuplicates ?? []) {
      const hit = out.find((x) => x.name === d.name && x.moduleRange === d.moduleRange && x.appVersion === d.appVersion)
      if (hit) {
        hit.lines.push(l.key)
        hit.om.push(l.version)
      } else out.push({ ...d, lines: [l.key], om: [l.version] })
    }
  return out.sort((a, b) => a.name.localeCompare(b.name))
}

const listText = (xs: readonly string[]): string =>
  xs.length <= 1 ? (xs[0] ?? '') : `${xs.slice(0, -1).join(', ')} and ${xs[xs.length - 1]}`

/**
 * The lint text of spec 6.6 for one bundled package: `Bundles @tanstack/react-table 9.2.6 while Open Mercato 0.9.0
 * ships 9.3.1. Two copies break types. Move it to peerDependencies.` Over several lines it names the lines.
 */
export function hostDuplicateText(f: HostDuplicateFinding): string {
  const where = f.om.length === 1 ? `Open Mercato ${f.om[0]}` : `a new app on ${listText(f.lines)}`
  return `Bundles ${f.name} ${f.moduleRange} while ${where} ships ${f.appVersion}. Two copies break types. Move it to peerDependencies.`
}

/**
 * The likely cause of a failed typecheck when the module bundles host packages (D-OPEN-4: help, not blame): `The
 * package bundles its own @tanstack/react-table and @tanstack/react-query; two copies break types. Move them to
 * peerDependencies`. Null without findings.
 */
export function hostDuplicateFix(fs: readonly HostDuplicateFinding[]): string | null {
  const names = [...new Set(fs.map((f) => f.name))]
  if (names.length === 0) return null
  return `The package bundles its own ${listText(names)}, and two copies break types. Move ${names.length === 1 ? 'it' : 'them'} to peerDependencies`
}

/**
 * Whether a failed typecheck reads like two copies of a bundled package: the excerpt names one of them, or has the
 * errors two copies of one type give (TS2321 excessive stack depth, TS2719 two types with one name, TS2322 and TS2345
 * not assignable). The page then names the bundled packages as the likely cause.
 */
export function duplicateTypeError(excerpt: string | null | undefined, names: readonly string[]): boolean {
  if (!excerpt || names.length === 0) return false
  return names.some((n) => excerpt.includes(n)) || /\bTS(2321|2719|2322|2345)\b/.test(excerpt)
}
