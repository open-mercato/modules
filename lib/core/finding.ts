// The one sentence of a failed step (review r9): why it failed, when its excerpt says it plainly, else what it
// printed first. The module page, the drawer, /compat, /r, the agent card and `check_compat` all read it from here, so
// people and agents get the same words (spec 1.1 item 4). Isomorphic: no Node APIs (lib/receipts/classify.ts, which
// runs in `collect`, re-exports the explanation).

/** A smoke check refused with 403 because its route needs features (`{"requiredFeatures":["workflows.view"]}`). */
export interface ForbiddenRoute {
  /** `GET /api/events`, or null when the excerpt starts at the response body (receipts collected before round 5). */
  route: string | null
  features: string[]
  /** Module IDs of the features (`workflows` of `workflows.view`), in the order of the features. */
  modules: string[]
}

const FEATURE_RE = /^[a-z][a-z0-9_]*(?:\.[a-z0-9_*]+)+$/i

/** Reads a 403 with `requiredFeatures` from a smoke excerpt, or null. */
export function forbiddenRoute(excerpt: string | null | undefined): ForbiddenRoute | null {
  if (!excerpt) return null
  const body = /"requiredFeatures"\s*:\s*\[([^\]]*)\]/.exec(excerpt)
  if (!body) return null
  const features = (body[1] ?? '')
    .split(',')
    .map((s) => s.trim().replace(/^"|"$/g, ''))
    .filter((s) => FEATURE_RE.test(s))
  if (features.length === 0) return null
  const check = /^smoke: FAIL .*?\b(GET|POST|PUT|PATCH|DELETE) (\/\S*) -> 403\b/m.exec(excerpt)
  const modules = [...new Set(features.map((f) => f.split('.')[0] as string))]
  return { route: check ? `${check[1]} ${check[2]}` : null, features, modules }
}

/** A route of the module facts, as much as the smoke check needs (`facts.modules[].http.routes[]`). */
export interface RouteFact {
  method: string
  path: string
  requireAuth: boolean | null
  requireFeatures: readonly string[]
}

export interface ExplainContext {
  /**
   * Whether the `empty` starter preset of the receipt's line enables a module ID (data/presets.json, `built-in.json`
   * `inPresets`), or undefined when the catalog does not know. The receipts scaffold with `--preset empty`; the default
   * preset of create-mercato-app is `classic` (packages/create-app/src/lib/starter-presets.ts), whose src/modules.ts
   * enables more, workflows among them. So the sentence names the empty preset, never `a new app` (review r10). Open
   * Mercato refuses the features of a disabled module even to a superadmin (packages/core/src/modules/auth/AGENTS.md),
   * so a 403 for such a feature is the module's missing `requires`.
   */
  enabledInEmptyPreset?: (moduleId: string) => boolean | undefined
  /**
   * Routes of the installed version (its facts). An excerpt collected before the smoke check printed its route starts
   * at the response body: the route is then the one route the smoke check could call (an authenticated GET under
   * /api/) whose required features are exactly the refused ones, so the sentence still names it (review r9).
   */
  routes?: readonly RouteFact[]
  /**
   * The starter preset of the receipt's app (round 13): `classic` is a new app (`npx create-mercato-app` without
   * `--preset`), `empty` the signal in isolation. A sentence about what the app already has names it.
   */
  preset?: 'classic' | 'empty'
  /**
   * The package that registers a module ID in the receipt's app (data/presets.json of its line and preset):
   * `@open-mercato/core` for a built-in module, `@open-mercato/webhooks` for `webhooks` in a new app; undefined when
   * the app does not register it or the catalog does not know.
   */
  registeredBy?: (moduleId: string) => string | undefined
}

/**
 * `yarn mercato generate` (run by `module add`) refuses two modules with one backend page URL (round 13, the classic
 * night of 24 Oct: `[generate] Duplicate backend route pattern "/backend/webhooks" generated by modules "webhooks" and
 * "shipment_tracking". ...`).
 */
export const DUPLICATE_ROUTE_RE =
  /Duplicate backend route pattern "([^"\s]+)" generated by modules "([^"\s]+)" and "([^"\s]+)"/

/** The route and the two module IDs of a duplicate backend route in an excerpt, or null. */
export function duplicateRoute(
  excerpt: string | null | undefined,
): { route: string; modules: [string, string] } | null {
  const m = excerpt ? DUPLICATE_ROUTE_RE.exec(excerpt) : null
  return m ? { route: m[1] as string, modules: [m[2] as string, m[3] as string] } : null
}

const APP_LEAD: Readonly<Record<'classic' | 'empty', string>> = {
  classic: 'In a new app from the default preset, the module',
  empty: 'In an app from the empty preset, the module',
}

/**
 * The sentence of a duplicate backend route (round 13): `In a new app from the default preset, the module adds the
 * backend route /backend/webhooks, which the webhooks module (@open-mercato/webhooks) already has.` The module that
 * was there first is the one the app registers (`registeredBy`); a built-in one is called built-in. Without the app's
 * modules it names both and blames neither.
 */
export function duplicateRouteText(
  d: { route: string; modules: readonly [string, string] },
  ctx: Pick<ExplainContext, 'preset' | 'registeredBy'> = {},
): string {
  const [a, b] = d.modules
  const ra = ctx.registeredBy?.(a)
  const rb = ctx.registeredBy?.(b)
  if ((ra === undefined) === (rb === undefined))
    return `Two modules generate the backend route ${d.route}: ${a} and ${b}.`
  const [other, from] = ra !== undefined ? [a, ra] : [b, rb as string]
  const owner = from === '@open-mercato/core' ? `the built-in ${other} module` : `the ${other} module (${from})`
  const lead = ctx.preset ? APP_LEAD[ctx.preset] : 'The module'
  return `${lead} adds the backend route ${d.route}, which ${owner} already has.`
}

