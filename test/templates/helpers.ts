/** The default files of a template app, by path inside the app. */
export function templateFiles(): Record<string, string> {
  return {
    'package.json': `${JSON.stringify(PACKAGE_JSON, null, 2)}\n`,
    'yarn.lock': YARN_LOCK,
    LICENSE: MIT,
    'README.md': '# B2B portal\n',
    'src/modules.ts': SCAFFOLD_MODULES_TS,
    'src/official-modules.generated.ts': SCAFFOLD_OFFICIAL,
    'src/modules/quotes_portal/index.ts': 'export const metadata = {}\n',
  }
}

/**
 * The archive of a template app. `files` maps paths inside the app to text (null drops a default file); `extra` adds
 * raw entries, already under the top directory.
 */
export function templateArchive(
  files: Record<string, string | null> = {},
  extra: TarEntry[] = [],
  top = `acme-b2b-portal-${SHA}`,
): Uint8Array {
  const all: Record<string, string | null> = { ...templateFiles(), ...files }
  const entries: TarEntry[] = [{ path: `${top}/`, type: 'dir' }]
  for (const [p, c] of Object.entries(all)) if (c !== null) entries.push({ path: `${top}/${p}`, content: c })
  return makeTarball([...entries, ...extra])
}
