/** One Yarn 4 lockfile entry. */
export function lockEntry(name: string, version: string, deps: Record<string, string> = {}): string {
  const lines = [`"${name}@npm:${version}":`, `  version: ${version}`, `  resolution: "${name}@npm:${version}"`]
  if (Object.keys(deps).length > 0) {
    lines.push('  dependencies:')
    for (const [d, v] of Object.entries(deps)) lines.push(`    "${d}": "npm:${v}"`)
  }
  lines.push('  checksum: 10c0/0000', '  languageName: node', '  linkType: hard', '')
  return lines.join('\n')
}

export function lockfile(entries: string[]): string {
  return [
    '# This file is generated by running "yarn install" inside your project.',
    '# Manual changes might be lost - proceed with caution!',
    '',
    '__metadata:',
    '  version: 10',
    '  cacheKey: 10c0',
    '',
    ...entries,
  ].join('\n')
}

